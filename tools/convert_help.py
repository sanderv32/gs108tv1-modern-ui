def balance_p(b):
    """Drop </p> without an open <p> (Netgear's cells often contain unbalanced paragraphs)."""
    out, depth = [], 0
    for tok in re.split(r"(</?p\b[^>]*>)", b, flags=re.I):
        low = tok.lower()
        if low.startswith("<p"):
            if depth:            # unclosed <p> before a new one: close it
                out.append("</p>")
            depth = 1
        elif low.startswith("</p"):
            if not depth:
                continue
            depth = 0
        out.append(tok)
    if depth:
        out.append("</p>")
    return "".join(out)


def clean(body):
    """Old layout tables -> plain blocks; keep text, lists, emphasis, links and anchors."""
    b = re.sub(r"<!--.*?-->", "", body, flags=re.S)
    b = re.sub(r"<img[^>]*>", "", b, flags=re.I)
    b = re.sub(r"<td[^>]*class=\"?spacer[^>]*>\s*(&nbsp;)?\s*</td>", "", b, flags=re.I)
    # section headings
    b = re.sub(r"<td[^>]*class=\"?(font11Bold|font12Bold)[^>]*>(.*?)</td>", r"<h2>\2</h2>", b, flags=re.I | re.S)
    # remaining cells -> paragraphs
    b = re.sub(r"<td[^>]*>", "<p>", b, flags=re.I)
    b = re.sub(r"</td>", "</p>", b, flags=re.I)
    b = re.sub(r"</?(table|tbody|tr|div|span|font)[^>]*>", "", b, flags=re.I)
    b = re.sub(r"\s(class|width|height|valign|align|style|bgcolor|border)=(\"[^\"]*\"|'[^']*'|[^\s>]+)", "", b, flags=re.I)
    b = re.sub(r"<p>\s*<p>", "<p>", b, flags=re.I)                       # stray <p> from unclosed <p> in cells
    b = re.sub(r"<p>\s*((?:<(?:ol|ul|h2)\b).*?)</p>", r"\1", b, flags=re.I | re.S)  # lists/headings need no <p>
    b = re.sub(r"<p>\s*(&nbsp;|\s)*</p>", "", b, flags=re.I)
    b = re.sub(r"(<br\s*/?>\s*)+(</li>)", r"\2", b, flags=re.I)
    b = balance_p(b)
    b = re.sub(r"[ \t]+", " ", b)
    b = re.sub(r"\s*\n\s*", "\n", b).strip()
    return b


def convert(name, src):
    if "BEGIN MAIN BODY COPY" in src:
        t = re.search(r'class="popWhite10">(.*?)</span>', src, re.S)
        title = re.sub(r"\s+", " ", t.group(1)).strip() if t else "Help"
        body = src[src.index("BEGIN MAIN BODY COPY"):src.index("END MAIN BODY COPY")]
        body = body[body.index("-->") + 3:]
        body = body[:body.rindex("<!--")] if "<!--" in body else body
        return PAGE % {"title": title, "body": clean(body)}
    if name == "help1.html":
        body = src[src.index('id="mid"'):]
        body = body[body.index(">") + 1:]
        body = body[:body.rindex("</div>")] if "</div>" in body else body
        return PAGE % {"title": "Help", "body": clean(body)}
    if name == "help.html":
        return PAGE % {"title": "Help", "body": '<p>See the <a href="help1.html">general help</a>, or use the '
                       '<b>?</b> next to each section of the web interface.</p>'}
    raise ValueError("unknown help layout: " + name)


def help_pages(stock):
    """{content id: bytes} of the converted pop-ups plus pop_styles.css, from the stock files."""
    out = {n: convert(n, src.decode("latin1")).encode("latin1") for n, src in sorted(stock.items())
           if "help" in n and n.endswith(".html")}
    out["pop_styles.css"] = CSS.encode()
    return out


def main():
    stock, _ = fw.stock_tree(os.path.join(ROOT, "GS108T-V3.0.4.10.bin"))
    pages = help_pages(stock)
    for n, blob in pages.items():
        with open(os.path.join(OUT, n), "wb") as f:
            f.write(blob)
    print("converted %d help pages" % (len(pages) - 1))


if __name__ == "__main__":
    main()
